on public.list_movies for insert
to authenticated
with check (exists (
  select 1 from public.lists
  where lists.id = list_movies.list_id and lists.user_id = (select auth.uid())
));

create policy "Users can remove movies from their lists"
on public.list_movies for delete
to authenticated
using (exists (
  select 1 from public.lists
  where lists.id = list_movies.list_id and lists.user_id = (select auth.uid())
));

