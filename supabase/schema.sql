-- Fotos de perfil: bucket público de lectura; cada usuario solo sube y
-- reemplaza archivos dentro de su propia carpeta ({user_id}/avatar.ext).
insert into storage.buckets (id, name, public)
values ('avatars', 'avatars', true)
on conflict (id) do update set public = true;

drop policy if exists "Avatars are publicly readable" on storage.objects;
drop policy if exists "Users can upload their avatar" on storage.objects;
drop policy if exists "Users can replace their avatar" on storage.objects;

create policy "Avatars are publicly readable"
on storage.objects for select
to public
using (bucket_id = 'avatars');

create policy "Users can upload their avatar"
on storage.objects for insert
to authenticated
with check (bucket_id = 'avatars' and (storage.foldername(name))[1] = (select auth.uid())::text);

create policy "Users can replace their avatar"
on storage.objects for update
to authenticated
using (bucket_id = 'avatars' and (storage.foldername(name))[1] = (select auth.uid())::text)
with check (bucket_id = 'avatars' and (storage.foldername(name))[1] = (select auth.uid())::text);
