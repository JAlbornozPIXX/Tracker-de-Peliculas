-- Calificadores (reacciones con emoji). Los 4 base tienen user_id = null y los
-- ve cualquier usuario; los que crea un usuario solo los ve él.
create table if not exists public.reactions (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade,
  emoji text not null check (char_length(btrim(emoji)) between 1 and 16),
  name text not null check (char_length(btrim(name)) between 1 and 20),
  created_at timestamptz not null default now()
);

create index if not exists reactions_user_id_idx on public.reactions (user_id);
create unique index if not exists reactions_base_name_key on public.reactions (name) where user_id is null;

