create table if not exists public.movies (
  id bigint generated by default as identity primary key,
  title text not null,
  overview text,
  poster_url text,
  release_date date,
  genre text[] not null default '{}',
  created_at timestamptz not null default now()
);

create table if not exists public.user_movies (
  user_id uuid not null references auth.users(id) on delete cascade,
  movie_id bigint not null references public.movies(id) on delete cascade,
  status text not null check (status in ('watchlist', 'watching', 'watched')),
  rating numeric(2, 1) check (rating is null or (rating >= 0 and rating <= 5)),
  notes text,
  updated_at timestamptz not null default now(),
  primary key (user_id, movie_id)
);

alter table public.movies enable row level security;
alter table public.user_movies enable row level security;

drop policy if exists "Anyone can read movies" on public.movies;
drop policy if exists "Users can read their movie tracking" on public.user_movies;
drop policy if exists "Users can add their movie tracking" on public.user_movies;
drop policy if exists "Users can update their movie tracking" on public.user_movies;
drop policy if exists "Users can delete their movie tracking" on public.user_movies;

create policy "Anyone can read movies"
on public.movies for select
to anon, authenticated
using (true);

create policy "Users can read their movie tracking"
on public.user_movies for select
to authenticated
using ((select auth.uid()) = user_id);

create policy "Users can add their movie tracking"
on public.user_movies for insert
to authenticated
with check ((select auth.uid()) = user_id);

create policy "Users can update their movie tracking"
on public.user_movies for update
to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

create policy "Users can delete their movie tracking"
on public.user_movies for delete
to authenticated
using ((select auth.uid()) = user_id);

grant select on public.movies to anon, authenticated;
grant select, insert, update, delete on public.user_movies to authenticated;

-- Títulos traídos de TheMovieDB: tmdb_id + media_type identifican el título de origen.
alter table public.movies add column if not exists duration_minutes integer;
alter table public.movies add column if not exists tmdb_id bigint;
alter table public.movies add column if not exists media_type text check (media_type in ('movie', 'tv'));

create unique index if not exists movies_tmdb_id_media_type_key
on public.movies (tmdb_id, media_type);

drop policy if exists "Users can add movies from TMDB" on public.movies;

create policy "Users can add movies from TMDB"
on public.movies for insert
to authenticated
with check (tmdb_id is not null and media_type is not null);

grant insert on public.movies to authenticated;

-- Listas personales: una película puede estar en varias listas.
create table if not exists public.lists (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null check (char_length(btrim(name)) between 1 and 60),
  created_at timestamptz not null default now()
);

create table if not exists public.list_movies (
  list_id bigint not null references public.lists(id) on delete cascade,
  movie_id bigint not null references public.movies(id) on delete cascade,
  added_at timestamptz not null default now(),
  primary key (list_id, movie_id)
);

create index if not exists lists_user_id_idx on public.lists (user_id);
create index if not exists list_movies_movie_id_idx on public.list_movies (movie_id);

alter table public.lists enable row level security;
alter table public.list_movies enable row level security;

