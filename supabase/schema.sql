-- Calificadores que cada usuario marcó en cada película.
create table if not exists public.user_movie_reactions (
  user_id uuid not null references auth.users(id) on delete cascade,
  movie_id bigint not null references public.movies(id) on delete cascade,
  reaction_id bigint not null references public.reactions(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, movie_id, reaction_id)
);

create index if not exists user_movie_reactions_movie_id_idx on public.user_movie_reactions (movie_id);
create index if not exists user_movie_reactions_reaction_id_idx on public.user_movie_reactions (reaction_id);

