-- Orden manual de playlists y colecciones (p. ej. una saga). Las filas sin
-- posición se numeran al final de su lista por fecha en que se agregaron.
alter table public.list_movies add column if not exists position integer;

update public.list_movies as lm
set position = numbered.position
from (
  select
    list_id,
    movie_id,
    (select coalesce(max(p.position), 0) from public.list_movies as p where p.list_id = l.list_id)
      + row_number() over (partition by list_id order by added_at, movie_id) as position
  from public.list_movies as l
  where position is null
) as numbered
where lm.list_id = numbered.list_id and lm.movie_id = numbered.movie_id;

-- Una película agregada sin posición queda última en su lista.
create or replace function public.set_list_movie_position()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.position is null then
    select coalesce(max(position), 0) + 1 into new.position
    from public.list_movies
    where list_id = new.list_id;
  end if;
  return new;
end;
$$;

